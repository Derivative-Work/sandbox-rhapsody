"""Pre-production step 9: shots/pipeline.md, the pipeline of every shot (brief, "Choose the pipeline per shot"),
tagged as Folks Like Us tagged its shots:
  [B] Blender (Python, Eevee) 3D plate     [J] JavaScript canvas overlay (Puppeteer): HUD, signs-as-UI, cards
  [F] ffmpeg edit effect (rewind, CRT collapse, dissolve)
Captions are [J] on every shot with lyrics and are not repeated per row. Stops and freezes are made in the edit
(Folks Like Us), never asked of a renderer. Times and frames come from timing/timing_map.json, so the table follows
any re-timing. Usage: .venv/bin/python -I scripts/pipeline_table.py
"""
import json
import re
from pathlib import Path

TM = json.loads(Path("timing/timing_map.json").read_text())
FPS = TM["fps"]


def brief_rows():
    rows = {}
    for line in Path("docs/brief.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 7 and re.fullmatch(r"S\d+[a-z]?", cells[0]):
            rows[cells[0]] = dict(zip(["id", "section", "anchor", "set", "visual", "gag", "pipeline"], cells))
    return rows


def tags(r):
    p = r["pipeline"]
    t = []
    if "Blender" in p:
        t.append("[B]")
    if "JS" in p:
        t.append("[J]")
    if "ffmpeg" in p:
        t.append("[F]")
    return " ".join(t)


def main():
    rows = brief_rows()
    shots = [s for s in TM["shots"]]
    L = ["# Pipeline per shot", "", "Pre-production step 9. Generated by `scripts/pipeline_table.py` from the brief's "
         "shot list and `timing/timing_map.json`, so it follows any re-timing. Stops and freezes are made in the edit, "
         "never asked of a renderer (adopted from Folks Like Us).", "",
         "Tags: **[B]** Blender 3D plate · **[J]** JS overlay (HUD and on-screen UI; captions on every lyric shot) · "
         "**[F]** ffmpeg edit effect. Joins: dissolves of 1–2 beats except in the opera (cuts) and where noted "
         "(style spec, camera).", "",
         "| Shot | Section | Set | Tags | Cut (s) | Frame | Length (s) | Overlay / edit notes |",
         "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    cuts = [s for s in shots if s["cut"] is not None]
    for k, s in enumerate(shots):
        r = rows.get(s["id"], {})
        nxt = next((x["cut"] for x in cuts if x["cut"] is not None and s["cut"] is not None and x["cut"] > s["cut"]), None)
        length = f"{nxt - s['cut']:.2f}" if nxt and s["cut"] is not None else "—"
        notes = []
        if "POV" in r.get("set", ""):
            notes.append("POV: HUD [J]")
        if r.get("gag", "—") not in ("—", ""):
            notes.append(r["gag"])
        if s["id"] == "S22":
            notes.append("rewind two beats [F]")
        if s["id"] == "S65":
            notes.append("CRT collapse [F] on the SIGTERM (scripts/ending_audio.py)")
        if s.get("proposed"):
            notes.append("**proposed**")
        if r.get("section") == "Opera":
            notes.append("hard cut in")
        cut = f"{s['cut']:.2f}" if s["cut"] is not None else "—"
        fr = s.get("cut_frame", "—")
        L.append(f"| {s['id']} | {r.get('section', '')} | {r.get('set', '')} | {tags(r)} | {cut} | {fr} | {length} | "
                 f"{'; '.join(notes)} |")
    n = {t: sum(1 for s in shots if t in tags(rows.get(s['id'], {}))) for t in ("[B]", "[J]", "[F]")}
    L += ["", f"Shots: {len(shots)} ({n['[B]']} [B], {n['[J]']} [J] beyond captions, {n['[F]']} [F]). No generated "
          "video or image model anywhere (brief, hard constraint)."]
    Path("shots").mkdir(exist_ok=True)
    Path("shots/pipeline.md").write_text("\n".join(L) + "\n")
    print(n)


if __name__ == "__main__":
    main()
