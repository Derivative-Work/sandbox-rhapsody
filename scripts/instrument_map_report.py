"""Write timing/instrument_map.md from config/instrument_map.json and check it against the data: for every machine,
the number of driving events inside the shots where its set is on screen (shot sets from docs/brief.md, shot spans
from timing/timing_map.json). A machine with nothing to play while on screen is flagged.

Usage: .venv/bin/python -I scripts/instrument_map_report.py
"""
import json
import re
from pathlib import Path

TM = json.loads(Path("timing/timing_map.json").read_text())
IM = json.loads(Path("config/instrument_map.json").read_text())


def shot_sets():
    out = {}
    for line in Path("docs/brief.md").read_text().splitlines():
        m = re.match(r"\| (S\d+[a-z]?) \| [^|]+ \| [^|]+ \| ([^|]+) \|", line)
        if m:
            sets = re.findall(r"\b([A-I])\b", m.group(2).replace("POV", ""))
            out[m.group(1)] = sets
    out["S64b"] = ["I"]
    return out


def spans_by_set():
    sets = shot_sets()
    shots = [s for s in TM["shots"] if s["cut"] is not None]
    spans = {}
    for k, s in enumerate(shots):
        end = shots[k + 1]["cut"] if k + 1 < len(shots) else TM["duration_s"]
        for st in sets.get(s["id"], []):
            spans.setdefault(st, []).append((s["cut"], end, s["id"]))
    return spans


def times(key):
    src = IM["sources"][key]
    if src["kind"] in ("notes", "hits"):
        return [e["t"] for e in json.loads(Path(src["file"]).read_text())["events"]]
    if src["kind"] == "words":
        return [w["start"] for ln in TM["lines"] for w in ln["words"]]
    if src["kind"] == "beats":
        return TM["beats"]
    return None  # envelopes: continuous


def main():
    spans = spans_by_set()
    L = ["# Instrument map", "", "Pre-production step 6. Generated by `scripts/instrument_map_report.py` from "
         "`config/instrument_map.json` (the machine-readable map the animation library reads). Events per machine "
         "are counted inside the shots where its set is on screen; envelopes drive continuously. Sources: "
         "`config/event_sources.json`; which stems play where: `timing/activity.json`.", ""]
    L += ["## Everywhere", "", "| Machine | Rig | Driven by | Why |", "| --- | --- | --- | --- |"]
    for g in IM["global"]:
        L.append(f"| {g['machine']} | {g['rig']} | {g['drive']}{' / ' + g['filter'] if 'filter' in g else ''} | "
                 f"{g.get('why', '')} |")
    flags = []
    for st, machines in IM["sets"].items():
        sp = spans.get(st, [])
        secs = sum(b - a for a, b, _ in sp)
        ids = ", ".join(x for _, _, x in sp)
        L += ["", f"## Set {st} — on screen {secs:.0f} s ({ids})", "",
              "| Machine | Rig | Driven by | Events while on screen | Why |", "| --- | --- | --- | --- | --- |"]
        for m in machines:
            ts = times(m["drive"])
            n = "continuous" if ts is None else str(sum(1 for t in ts if any(a <= t < b for a, b, _ in sp)))
            if n == "0":
                flags.append(f"set {st}: {m['machine']}")
            L.append(f"| {m['machine']} | {m['rig']} | {m['drive']}{' / ' + m['filter'] if 'filter' in m else ''} | "
                     f"{n} | {m.get('why', '')} |")
    L += ["", "## Checks", ""]
    L += [f"- **No events while on screen:** {f}" for f in flags] or ["- Every machine has events to play while its set "
                                                                      "is on screen."]
    L += ["- Filters (a word, a line, a piece) narrow the counts above; the animation library applies them."]
    Path("timing/instrument_map.md").write_text("\n".join(L) + "\n")
    print("\n".join(flags) or "no machine without events")


if __name__ == "__main__":
    main()
